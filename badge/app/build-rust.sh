#!/usr/bin/env bash
# Build the Rust core (dices-badge staticlib) for a target and generate
# generated/link.cmake for the Tactility app to link against.
#
# Usage: ./build-rust.sh [target-triple]
#   (default: the host target, for quick smoke builds)
#
# On ESP-IDF targets (e.g. xtensa-esp32s3-espidf) this must run where the
# espup toolchain is available (see Dockerfile.rust).
set -euo pipefail

TARGET="${1:-}"
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
APP_DIR="${REPO_ROOT}/badge/app"
GENERATED_DIR="${APP_DIR}/generated"
mkdir -p "${GENERATED_DIR}"

CARGO_ARGS=(--manifest-path "${REPO_ROOT}/Cargo.toml" -p dices-badge)
if [[ -n "${TARGET}" ]]; then
    CARGO_ARGS+=(--target "${TARGET}")
fi

echo ">> cargo build ${CARGO_ARGS[*]}"
cargo build "${CARGO_ARGS[@]}"

# Locate the built staticlib and rlib
PROFILE_DIR="${CARGO_TARGET_DIR:-${REPO_ROOT}/target}/debug"
if [[ -n "${TARGET}" ]]; then
    ARTIFACT_DIR="${PROFILE_DIR}/${TARGET}"
else
    ARTIFACT_DIR="${PROFILE_DIR}"
fi
STATICLIB="${ARTIFACT_DIR}/libdices_badge.a"
RLIB="$(ls "${ARTIFACT_DIR}"/libdices_badge*.rlib | head -n1)"
echo ">> staticlib: ${STATICLIB}"
echo ">> rlib:      ${RLIB}"

# Rust std archives the consumer must link after the staticlib. rustc used to
# report these via a `native-static-libs` note, which current rustc no longer
# prints for staticlib builds, so instead we take every archive of the target's
# rustlib directory (unused members are skipped by the linker) and link them
# inside a linker group, which makes the order irrelevant.
SYSROOT="$(rustc ${TARGET:+--target "${TARGET}"} --print sysroot)"
if [[ -n "${TARGET}" ]]; then
    RUSTLIB_DIR="${SYSROOT}/lib/rustlib/${TARGET}/lib"
else
    HOST="$(rustc -vV | grep '^host: ' | cut -d' ' -f2)"
    RUSTLIB_DIR="${SYSROOT}/lib/rustlib/${HOST}/lib"
fi
if [[ ! -d "${RUSTLIB_DIR}" ]]; then
    echo "error: rustlib directory not found: ${RUSTLIB_DIR}" >&2
    exit 1
fi

echo ">> rustlib dir: ${RUSTLIB_DIR}"
CMAKE_LIBS="\"-Wl,--start-group\""
for archive in "${RUSTLIB_DIR}"/*.rlib "${RUSTLIB_DIR}"/*.a; do
    [[ -e "${archive}" ]] || continue
    CMAKE_LIBS+=" \"${archive}\""
done
CMAKE_LIBS+=" \"-Wl,--end-group\""

cat > "${GENERATED_DIR}/link.cmake" <<EOF
# Generated by build-rust.sh - do not edit
set(DICES_STATICLIB "${STATICLIB}")
set(DICES_LINK_LIBS ${CMAKE_LIBS})
EOF

echo ">> wrote ${GENERATED_DIR}/link.cmake"
cat "${GENERATED_DIR}/link.cmake"
